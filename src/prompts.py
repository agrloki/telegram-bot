def get_system_prompt(style: str) -> str:
    """
    Получить системный промпт для указанного стиля.

    Args:
        style: Стиль промпта (default, hk47-light, hk47)

    Returns:
        Системный промпт для указанного стиля или промпт по умолчанию
    """
    return SYSTEM_PROMPTS.get(style.lower(), SYSTEM_PROMPTS["default"])

